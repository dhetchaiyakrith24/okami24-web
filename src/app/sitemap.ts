import type { MetadataRoute } from "next";
import { allProducts } from "@/data/products";
import { categoriesWithProducts } from "@/lib/category-visibility";
import { guides } from "@/data/guides";
import { technologyEntries } from "@/data/technology";
import { flavorFamilies } from "@/data/flavors";
import { getPublishedProducts } from "@/data/shipnity-seed/storefront-bridge";
import { SITE_URL as BASE_URL } from "@/lib/seo";
import { brandsWithProducts } from "@/lib/brand-visibility";
import { contentLastModified, familyLastModified, legacyProductSource, type ContentFamily } from "@/lib/content-dates";

// Round "search-price" batch 3 (2026-09-22): `lastModified` used to be `new Date()` — the build
// time, the same on all 105 URLs, so every deploy told crawlers the privacy page had just changed.
// Now each URL carries the last git commit that touched the files its content comes from
// (src/lib/content-dates.ts → src/data/content-dates.json, regenerated by
// scripts/content-dates.ts and guarded by content-dates-contract-test.ts). Round "share-deadend"
// (2026-09-22) then dropped the empty categories, so the count is no longer a fixed 105 — it is
// whatever the catalog currently justifies, and every gate counts it from this file.
//
// Round "leftovers" (2026-09-22): the four tool pages /compare /finder /search /favorites are
// gone from this list. Each one sets `NOINDEX_FOLLOW` in its own generateMetadata, so listing
// them here told a crawler "index this" and the page itself said "do not" — the same mixed signal
// Search Console reports as "noindex", and the same rule the empty categories and empty brand
// pages already follow below: if the page says noindex, the sitemap does not offer it. The URLs
// keep working and stay reachable through the footer's Tools column, which is how a visitor finds
// them anyway; only the crawler invitation is withdrawn. `sitemap-noindex-contract-test.ts` reads
// the page files and fails the build if the two ever disagree again, for any page, not just these
// four — one mechanism, not a second rule to remember.
const STATIC_ROUTES: Record<string, ContentFamily> = {
  "": "home",
  "/products": "productsIndex",
  "/e-liquid": "eLiquid",
  "/guides": "guides",
  "/technology": "technology",
  "/faq": "faq",
  "/about": "about",
  "/how-to-order": "howToOrder",
  "/shipping": "shipping",
  "/warranty": "warranty",
  "/contact": "contact",
  "/privacy": "privacy",
};

export default function sitemap(): MetadataRoute.Sitemap {
  const routes: MetadataRoute.Sitemap = Object.entries(STATIC_ROUTES).map(([path, family]) => ({
    url: `${BASE_URL}${path}`,
    lastModified: familyLastModified(family),
  }));

  // Round "share-deadend" batch 2 (2026-09-22): only categories that actually hold a product —
  // the same rule, and the same reason, as `brandsWithProducts()` below. An empty category page
  // is noindexed (see products/[slug]/page.tsx), so offering it to a crawler here would be the
  // mixed signal Search Console reports as "noindex". The URL keeps working and comes back into
  // the sitemap by itself the day the category has stock.
  const categoryDate = familyLastModified("category");
  for (const c of categoriesWithProducts()) routes.push({ url: `${BASE_URL}/products/${c.slug}`, lastModified: categoryDate });
  for (const p of allProducts) routes.push({ url: `${BASE_URL}/products/${p.slug}`, lastModified: contentLastModified(legacyProductSource(p.brandId)) });
  // Real, published ProductMaster products only — never the DEV-preview pool (see
  // storefront-bridge.ts). Grows automatically as more products get genuine owner publication
  // approval (see publication-approvals.ts) — no per-product edit needed here.
  const publishedDate = familyLastModified("publishedProduct");
  for (const p of getPublishedProducts()) routes.push({ url: `${BASE_URL}/products/${p.slug}`, lastModified: publishedDate });
  // Only brands with a real product right now — a brand page with zero products is noindexed
  // (see brands/[brand]/page.tsx's generateMetadata), so it has no business being offered to a
  // crawler via the sitemap either. Same list `brandsWithProducts()` already builds for footer/
  // about-page navigation — one source of truth for "is this brand real yet."
  const brandDate = familyLastModified("brand");
  for (const b of brandsWithProducts()) routes.push({ url: `${BASE_URL}/brands/${b.slug}`, lastModified: brandDate });
  const guidesDate = familyLastModified("guides");
  for (const g of guides) routes.push({ url: `${BASE_URL}/guides/${g.slug}`, lastModified: guidesDate });
  const technologyDate = familyLastModified("technology");
  for (const t of technologyEntries) routes.push({ url: `${BASE_URL}/technology/${t.slug}`, lastModified: technologyDate });
  const eLiquidDate = familyLastModified("eLiquid");
  for (const f of flavorFamilies) routes.push({ url: `${BASE_URL}/e-liquid/${f.slug}`, lastModified: eLiquidDate });

  return routes;
}
