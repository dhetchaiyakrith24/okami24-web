import { rawActiveParents, excludedNonProductRows, type RawActiveParent } from "./active-catalog-source";
import { classifyParentChildren, type OptionType, type Provenance, type ChildRole } from "./classify";
import { MAX_SEED, MAX_SEED_DATE } from "./max-seed";
import { OWNER_APPROVED_PUBLICATION } from "./publication-approvals";

/**
 * Round list19 (17/10): the seed moves off the OLD Shipnity export (31/08) onto Shipnity MAX (`max-seed.ts`, generated by
 * scripts/max-seed-gen.js) — BSOT §4: only Max is used. Stage 1 keeps the live site identical: FROZEN records keep their 31/08
 * children and price reference (every published record + the SEO line's TEREA); every other record takes Max's name, ราคาขาย and
 * ALL its children. A Max child that is not a plain "<parent>-<n>" code (a "Set-…" box sold at its own price, odd codes such as
 * "Pod-171-10aa") is not an option of the record — it is listed in `maxDroppedChildren` instead (one price per record).
 * Records Max no longer lists keep their 31/08 data (their pages, if any, are sold out through sku-map.ts — owner 08/10).
 */
/** Stage 2 (18/10): published records moved onto Max, a few per PR. The published-catalogue dump proves each move. */
export const MOVED_TO_MAX_IDS = new Set<string>(["Coil-72", "Coil-38", "Pod-150"]);
export const FROZEN_SEED_IDS = new Set<string>(
  [...Object.keys(OWNER_APPROVED_PUBLICATION), "IQOSHEET-15"].filter((id) => !MOVED_TO_MAX_IDS.has(id))
);
export const maxDroppedChildren: { shipnityProductId: string; shipnityVariantId: string; rawLabel: string; reason: string }[] = [];
export { MAX_SEED_DATE };

export interface ActiveChildRecord {
  shipnityVariantId: string;
  rawLabel: string;
  optionType: OptionType;
  optionTypeProvenance: Provenance;
  cleanedValue: string | null;
  packagingNote: string | null;
  /** How OKami24 interprets this child — see `ChildRole` doc in classify.ts. */
  childRole: ChildRole;
}

export interface ActiveParentRecord {
  shipnityProductId: string;
  name: string;
  operationalSellingPrice: number;
  /** Shipnity MAX's own parent code when it differs from `shipnityProductId` (Max re-coded it), else undefined. */
  maxParentId?: string;
  /** "max" = from max-seed.ts · "seed-2026-08-31" = the old export (frozen record, or not in Max). */
  source: "max" | "seed-2026-08-31";
  sourcePages: number[];
  children: ActiveChildRecord[];
}

type SeedInput = Omit<RawActiveParent, "operationalCost">;

function fromMax(raw: RawActiveParent): (SeedInput & { maxParentId?: string }) | null {
  if (FROZEN_SEED_IDS.has(raw.shipnityProductId)) return null;
  const m = MAX_SEED[raw.shipnityProductId];
  if (!m) return null;
  const prefixes = [raw.shipnityProductId, m.maxParentId];
  const children = m.children.filter((c) => {
    const ok = prefixes.some((pre) => c.shipnityVariantId.startsWith(pre + "-") && /^\d+$/.test(c.shipnityVariantId.slice(pre.length + 1)));
    if (!ok) maxDroppedChildren.push({ shipnityProductId: raw.shipnityProductId, shipnityVariantId: c.shipnityVariantId, rawLabel: c.rawLabel, reason: `not a plain child code (Max ราคาขาย ฿${c.sellingPrice})` });
    return ok;
  });
  return {
    shipnityProductId: raw.shipnityProductId,
    name: m.name,
    operationalSellingPrice: m.operationalSellingPrice,
    sourcePages: [],
    children: children.map((c) => ({ shipnityVariantId: c.shipnityVariantId, rawLabel: c.rawLabel })),
    ...(m.maxParentId !== raw.shipnityProductId ? { maxParentId: m.maxParentId } : {}),
  };
}

function buildParent(seedRaw: RawActiveParent): ActiveParentRecord {
  const max = fromMax(seedRaw);
  // operationalCost ("ต้นทุน") is never carried into a record (the site stores no cost); the old seed file still holds the
  // 31/08 values until its own move PR (editing it now would bump every product page's dateModified — content-dates.ts).
  const raw: SeedInput = max ?? seedRaw;
  // Classified as one batch per parent, not child-by-child — group-context reconciliation
  // (see classify.ts file header) needs every sibling's signal available at once.
  const classified = classifyParentChildren(
    raw.shipnityProductId,
    raw.children.map((c) => c.rawLabel)
  );
  return {
    shipnityProductId: raw.shipnityProductId,
    name: raw.name,
    operationalSellingPrice: raw.operationalSellingPrice,
    ...(max?.maxParentId ? { maxParentId: max.maxParentId } : {}),
    source: max ? "max" : "seed-2026-08-31",
    sourcePages: raw.sourcePages,
    children: raw.children.map((c, i) => ({
      shipnityVariantId: c.shipnityVariantId,
      rawLabel: c.rawLabel,
      ...classified[i],
    })),
  };
}

export const activeCatalogSeed: ActiveParentRecord[] = rawActiveParents.map(buildParent);

export { excludedNonProductRows };
