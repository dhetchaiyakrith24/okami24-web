function fromMax(raw: RawActiveParent): (SeedInput & { maxParentId?: string }) | null {
  if (FROZEN_SEED_IDS.has(raw.shipnityProductId)) return null;
  if (MAX_ONLY_IDS.includes(raw.shipnityProductId)) return null; // already built from Max by fromMaxOnly
  const m = MAX_SEED[raw.shipnityProductId];
  if (!m) return null;
  const prefixes = [raw.shipnityProductId, m.maxParentId];
  const hasParentPriced = m.children.some((c) => c.sellingPrice === m.operationalSellingPrice);
  const children = m.children.filter((c) => {
    const ok = prefixes.some((pre) => c.shipnityVariantId.startsWith(pre + "-") && /^\d+$/.test(c.shipnityVariantId.slice(pre.length + 1)));
    if (!ok) maxDroppedChildren.push({ shipnityProductId: raw.shipnityProductId, shipnityVariantId: c.shipnityVariantId, rawLabel: c.rawLabel, reason: `not a plain child code (Max ราคาขาย ฿${c.sellingPrice})` });
    // One price per product (as fromMaxOnly): a plain-coded child at another price than its siblings at the parent price is a bundle
    // (ELIQUID-1-1 ฿807, a Marbo multi-pack). A parent with no child at its own price (Pod-171) keeps every child.
    const samePrice = !ok || !hasParentPriced || c.sellingPrice === m.operationalSellingPrice;
    if (!samePrice) maxDroppedChildren.push({ shipnityProductId: raw.shipnityProductId, shipnityVariantId: c.shipnityVariantId, rawLabel: c.rawLabel, reason: `other price than the parent (Max ราคาขาย ฿${c.sellingPrice} vs ฿${m.operationalSellingPrice})` });
    return ok && samePrice;
  });
  return {
    shipnityProductId: raw.shipnityProductId,
    name: m.name,
    operationalSellingPrice: m.operationalSellingPrice,
    sourcePages: [],
    children: children.map((c) => ({ shipnityVariantId: c.shipnityVariantId, rawLabel: MAX_LABEL_FIX[c.shipnityVariantId] ?? c.rawLabel })),
    ...(m.maxParentId !== raw.shipnityProductId ? { maxParentId: m.maxParentId } : {}),
  };
}

function buildParent(seedRaw: RawActiveParent): ActiveParentRecord {
  const max = fromMax(seedRaw);
  // operationalCost ("ต้นทุน") is never carried into a record (the site stores no cost); the old seed file still holds the
  // 31/08 values until its own move PR (editing it now would bump every product page's dateModified — content-dates.ts).
  const raw: SeedInput = max ?? seedRaw;
  // Classified as one batch per parent, not child-by-child — group-context reconciliation
  // (see classify.ts file header) needs every sibling's signal available at once.
  const classified = classifyParentChildren(
    raw.shipnityProductId,
    raw.children.map((c) => c.rawLabel)
  );
  return {
    shipnityProductId: raw.shipnityProductId,
    name: raw.name,
    operationalSellingPrice: raw.operationalSellingPrice,
    ...(max?.maxParentId ? { maxParentId: max.maxParentId } : {}),
    source: max ? "max" : "seed-2026-08-31",
    sourcePages: raw.sourcePages,
    children: raw.children.map((c, i) => ({
      shipnityVariantId: c.shipnityVariantId,
      rawLabel: c.rawLabel,
      ...classified[i],
    })),
  };
}

/**
 * Max-only records (round list19 18/10): products Shipnity MAX sells that the old 31/08 export never had. Their children are
 * the Max rows whose parent is that code (Max gives them "Variation N" codes, not "<parent>-<n>"); a child at another
 * ราคาขาย than the parent (e.g. a loose pod listed under a kit) is not an option of the record — it goes to maxDroppedChildren.
 */
/** Max writes a kit's option as "<bundle> <flavour>" (KS kit: "เครื่อง + หัว Watermelon" = device + one pod); the record's option is
 *  the flavour, and the page text says what the kit holds. Prefix stripped per record, nothing else changes. */
const MAX_ONLY_LABEL_PREFIX: Record<string, string> = {
  "KS-QUIKPRO-KIT": "เครื่อง + หัว ",
  "NEXSWITCH-16K-KIT": "เครื่อง + หัวพอต ",
  "NEXSWITCH-16K-POD": "หัวพอต ",
};

/** Max-only records whose Max parent and children carry different prices, where the owner set ONE price for the parent and every
 *  option (owner in chat 2026-10-19: "ราคา Graple Freebase: ฿160.-" · "ราคา MQ Bar 22K: ฿390.-"). Every child is an option here; the
 *  price itself lives only in publication-approvals.ts. */
const OWNER_ONE_PRICE_MAX_ONLY = new Set<string>(["GRAPLE-FREEBASE", "MQ-BAR-22K"]);

function fromMaxOnly(id: string): RawActiveParent {
  const m = MAX_SEED[id];
  const children = m.children.filter((c) => {
    const ok = OWNER_ONE_PRICE_MAX_ONLY.has(id) || c.sellingPrice === m.operationalSellingPrice;
    if (!ok) maxDroppedChildren.push({ shipnityProductId: id, shipnityVariantId: c.shipnityVariantId, rawLabel: c.rawLabel, reason: `other price than the parent (Max ราคาขาย ฿${c.sellingPrice} vs ฿${m.operationalSellingPrice})` });
    return ok;
  });
  return {
    shipnityProductId: id,
    name: m.name,
    operationalSellingPrice: m.operationalSellingPrice,
    operationalCost: 0, // never read — buildParent drops cost; Max has no cost column
    sourcePages: [],
    children: children.map((c) => {
      const pre = MAX_ONLY_LABEL_PREFIX[id];
      const fixed = MAX_LABEL_FIX[c.shipnityVariantId];
      return { shipnityVariantId: c.shipnityVariantId, rawLabel: fixed ?? (pre && c.rawLabel.startsWith(pre) ? c.rawLabel.slice(pre.length) : c.rawLabel) };
    }),
  };
}

export const activeCatalogSeed: ActiveParentRecord[] = [
  ...rawActiveParents.map(buildParent),
  ...MAX_ONLY_IDS.map((id) => {
    const rec = buildParent(fromMaxOnly(id));
    return { ...rec, maxParentId: MAX_SEED[id].maxParentId, source: "max" as const };
  }),
];

