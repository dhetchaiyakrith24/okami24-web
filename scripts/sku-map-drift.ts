/**
 * Shipnity Max product list vs src/data/stock/sku-map.ts — rerun any time (owner 10/11 "never drift silently again").
 * Read only: the Max product page is opened in the app browser where the owner is signed in; nothing is clicked except the
 * page's own "แสดงเพิ่ม N รายการ" expanders. The product rows never leave the page — only the drift does. Rules =
 * src/lib/stock/sku-drift-rules.ts (fill · unknown · gone).
 *
 *   1. npx tsx scripts/sku-map-drift.ts snippet <out.js>
 *        writes a snippet that carries today's sku-map.
 *   2. open https://app.shipnitymax.com/product/product?page=1&per_page=1000 and run the snippet in the page (`await …`).
 *        The snippet is ~40 KB: an agent copies it with PowerShell `Get-Content -Raw … | Set-Clipboard`, adds a textarea to the
 *        page, pastes (ctrl+v) and evals its value — the code never has to pass through a chat. It answers with the counts.
 *        The drift JSON stays in window.__skuDrift: read it 900 characters at a time (a browser tool cuts near 1,000) —
 *        .slice(0, 900), .slice(900, 1800), … — and save the joined text as <drift.json>.
 *   3. npx tsx scripts/sku-map-drift.ts report <drift.json>
 *        prints the three lists.
 *   4. npx tsx scripts/sku-map-drift.ts apply <drift.json>
 *        writes ONLY the `fill` matches (same Max parent, name = option id word for word) into sku-map.ts; review the diff,
 *        then the normal PR flow. `unknown` and `gone` are for a person: a new colour/flavour of a listed product goes onto its
 *        page as well (catalog completeness), a vanished code usually becomes null.
 */
import fs from "node:fs";
import path from "node:path";
import { SHIPNITY_SKU_MAP } from "../src/data/stock/sku-map";
import { skuDrift, type Drift, type MapProduct } from "../src/lib/stock/sku-drift-rules";

const MAP_FILE = path.join(__dirname, "..", "src", "data", "stock", "sku-map.ts");

function mapProducts(): MapProduct[] {
  return Object.entries(SHIPNITY_SKU_MAP).map(([slug, e]) => ({
    slug,
    parent: e.parent,
    options: e.options ? { ...e.options } : { "": e.product ?? null },
  }));
}

/** The page reader: open every expander, read every row (code · name · price · [ดูราคาเทียบ] · มีของ/ไม่มีของ · [N ร้าน]). */
function pageReader(): string {
  return `
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  for (let round = 0; round < 40; round++) {
    const all = [...document.querySelectorAll("button, a, span, div")].filter((e) => /^\\s*(expand_more\\s*)?แสดงเพิ่ม \\d+ รายการ\\s*$/.test(e.innerText || ""));
    const btns = all.filter((b) => !all.some((o) => o !== b && b.contains(o)));
    if (!btns.length) break;
    for (const b of btns) (b.closest("button") || b).click();
    await wait(1500);
  }
  const L = document.body.innerText.split("\\n").map((s) => s.trim()).filter(Boolean);
  const rows = [];
  let parent = null;
  for (let i = 0; i < L.length - 3; i++) {
    if (!/^[\\d,]+\\.\\d\\d$/.test(L[i + 2])) continue;
    let j = i + 3, isParent = false;
    if (L[j] === "ดูราคาเทียบ") { isParent = true; j++; if (L[j] === "keyboard_arrow_right") j++; }
    if (!/^(มีของ|ไม่มีของ)$/.test(L[j])) continue;
    if (/ร้าน$/.test(L[j + 1] || "")) isParent = true;
    rows.push({ code: L[i], name: L[i + 1], parent: isParent ? null : parent, stock: L[j] === "มีของ" ? 1 : 0 });
    if (isParent) parent = L[i];
    i = j;
  }`;
}

function snippet(out: string): void {
  const body = `// GENERATED by scripts/sku-map-drift.ts on ${new Date().toISOString().slice(0, 10)} — run in the Shipnity Max product page.
(async () => {
  const __name = (f) => f;
  const skuDrift = ${skuDrift.toString()};
  const products = ${JSON.stringify(mapProducts())};
${pageReader()}
  const parents = rows.filter((r) => !r.parent).length;
  const drift = skuDrift(rows, products);
  window.__skuDrift = JSON.stringify({ readAt: new Date().toISOString(), parents, children: rows.length - parents, ...drift });
  return JSON.stringify({ parents, children: rows.length - parents, fill: drift.fill.length, unknown: drift.unknown.length, gone: drift.gone.length, chars: window.__skuDrift.length });
})();
`;
  fs.writeFileSync(out, body);
  console.log(`wrote ${out} (${body.length} chars) — run it on the Max product page, then read window.__skuDrift`);
}

function load(file: string): Drift & { readAt?: string; parents?: number; children?: number } {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function report(file: string): void {
  const d = load(file);
  console.log(`Max read ${d.readAt ?? "?"} · ${d.parents ?? "?"} products · ${d.children ?? "?"} colours/flavours`);
  console.log(`\nfill (${d.fill.length}) — null on the site, code found, name matches word for word:`);
  for (const f of d.fill) console.log(`  ${f.slug} / ${f.option} → ${f.code} (${f.name}, ${f.stock ? "มีของ" : "ไม่มีของ"})`);
  console.log(`\nunknown (${d.unknown.length}) — in Max, mapped by no site option:`);
  for (const u of d.unknown) console.log(`  ${u.code} ${u.name}${u.parent ? ` · under ${u.parent} ${u.parentName ?? ""}` : " · (product row)"}${u.slug ? ` · site product ${u.slug}` : " · not a site product"}`);
  console.log(`\ngone (${d.gone.length}) — mapped on the site, no longer in Max:`);
  for (const g of d.gone) console.log(`  ${g.slug} / ${g.option}: ${g.code}`);
}

function apply(file: string): void {
  const d = load(file);
  let src = fs.readFileSync(MAP_FILE, "utf8");
  let done = 0;
  for (const f of d.fill) {
    const start = src.indexOf(`  "${f.slug}": {`);
    const end = start < 0 ? -1 : src.indexOf("\n  } },", start);
    if (start < 0 || end < 0) { console.error(`skip ${f.slug}: product block not found`); continue; }
    const block = src.slice(start, end);
    const line = new RegExp(`(\\n\\s*"${f.option.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}": )(null|"check"),`);
    if (!line.test(block)) { console.error(`skip ${f.slug} / ${f.option}: not null in sku-map any more`); continue; }
    src = src.slice(0, start) + block.replace(line, `$1"${f.code}",`) + src.slice(end);
    done++;
  }
  fs.writeFileSync(MAP_FILE, src);
  console.log(`sku-map.ts: ${done} of ${d.fill.length} fill(s) written — review the diff, run the sku-map contract test`);
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === "snippet" && arg) snippet(arg);
else if (cmd === "report" && arg) report(arg);
else if (cmd === "apply" && arg) apply(arg);
else {
  console.error("usage: npx tsx scripts/sku-map-drift.ts snippet <out.js> | report <drift.json> | apply <drift.json>");
  process.exit(1);
}
