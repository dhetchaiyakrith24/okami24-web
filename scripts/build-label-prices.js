/* eslint-disable @typescript-eslint/no-require-imports -- plain Node CLI helper, CommonJS on purpose */
/**
 * Writes src/data/label-prices.ts from the owner-approved label-price table (owner 03/11, BSOT §5 "2026-11-02 — struck-through
 * label price"). The table is the TSV behind the artifact the owner approved (columns in_stock · brand · name · slug · price ·
 * label · pct); this script copies slug · price · label as they are — no price is typed or recomputed here.
 *
 *   node scripts/build-label-prices.js <path-to-label-prices.tsv>
 *
 * Left out: marbo-10k-clone (the lookalike the owner keeps out of every pick — HANDOFF §18; Friday's brief 03/11).
 * Fails (exit 1, nothing written) on a malformed row, a duplicate slug, or a label outside 10–20 % above its price.
 */
const fs = require("fs");
const path = require("path");

const EXCLUDE = new Set(["marbo-10k-clone"]);
const OUT = path.join(__dirname, "..", "src", "data", "label-prices.ts");

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-label-prices.js <label-prices.tsv>");
  process.exit(1);
}
const lines = fs.readFileSync(src, "utf8").replace(/^﻿/, "").split(/\r?\n/).filter((l) => l.trim() !== "");
const head = lines.shift().split("\t");
const col = (name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`column "${name}" missing`);
  return i;
};
const [iSlug, iPrice, iLabel] = [col("slug"), col("price"), col("label")];

const rows = [];
const errors = [];
const seen = new Set();
for (const line of lines) {
  const c = line.split("\t");
  const slug = c[iSlug];
  const price = Number(c[iPrice]);
  const label = Number(c[iLabel]);
  if (!/^[a-z0-9-]+$/.test(slug ?? "") || !Number.isInteger(price) || !Number.isInteger(label)) errors.push(`bad row: ${line}`);
  else if (seen.has(slug)) errors.push(`duplicate slug: ${slug}`);
  else if (label < price * 1.1 || label > price * 1.2) errors.push(`${slug}: label ${label} is not 10–20 % above ${price}`);
  else if (!EXCLUDE.has(slug)) rows.push({ slug, price, label });
  seen.add(slug);
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
rows.sort((a, b) => a.slug.localeCompare(b.slug));

const body = rows.map((r) => `  ${JSON.stringify(r.slug)}: { price: ${r.price}, label: ${r.label} },`).join("\n");
const out = `/**
 * GENERATED by scripts/build-label-prices.js from the owner-approved table (owner 03/11 "รันตามนั้นเลยได้และใส่ %",
 * BSOT §5 "2026-11-02 — struck-through label price"). Do not edit by hand — change the table and re-run the script.
 * slug → the selling price the label was approved against + the struck-through label price. Display only: nothing that
 * charges, totals, sends or describes a price to Google reads this file (src/data/label-prices-contract-test.ts).
 */
export const LABEL_PRICES: Readonly<Record<string, { price: number; label: number }>> = {
${body}
};
`;
fs.writeFileSync(OUT, out.replace(/\n/g, "\r\n")); // CRLF on disk (docs/HANDOFF.md §17 "CRLF")
console.log(`wrote ${path.relative(process.cwd(), OUT)} · ${rows.length} products · left out ${[...EXCLUDE].join(", ")}`);
